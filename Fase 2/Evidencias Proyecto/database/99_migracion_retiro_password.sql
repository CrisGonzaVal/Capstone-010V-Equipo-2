-- =====================================================
-- COMPUSTOCK ERP - MIGRACION 007: RETIRO DE password LOCAL
-- Base de datos: apt_erp
-- PostgreSQL 16
-- =====================================================
--
-- PROPOSITO
--   Clerk es la unica autoridad de autenticacion (Feature 006). La columna
--   `usuario.password` ya no se usa y se retira del esquema funcional
--   (Feature 007, AC-13). En instalaciones NUEVAS la columna nunca se crea:
--   el esquema limpio (`01_esquema.sql`) ya la omite. En bases YA
--   INICIALIZADAS sigue existiendo y hay que retirarla de forma explicita,
--   porque PostgreSQL solo ejecuta los scripts de /docker-entrypoint-initdb.d
--   cuando el volumen se crea por primera vez.
--
-- QUE HACE
--   Elimina UNICAMENTE la columna `usuario.password`. No reinicializa, no
--   trunca, no toca filas, secuencias ni otras tablas. Los usuarios, claves,
--   roles y relaciones se conservan intactos.
--
-- IDEMPOTENCIA
--   `DROP COLUMN IF EXISTS` no falla si la columna ya no existe: se puede
--   ejecutar las veces que hagan falta y tambien sobre una instalacion nueva,
--   donde resulta un no-op con el aviso "column ... does not exist, skipping".
--   Es seguro bajo `ON_ERROR_STOP=1`.
--
-- ORDEN DE EJECUCION
--   El prefijo `99_` garantiza que, si esta carpeta se monta en
--   /docker-entrypoint-initdb.d (volumen NUEVO), este script corre al final,
--   despues de `01_esquema.sql` y `02_datos_semilla.sql`. Alli es un no-op
--   porque el esquema nuevo ya no declara la columna. Mantener el orden
--   alfabetico: no renombrar a un prefijo que sortee antes de `01_`, o el
--   script correria antes de que exista la tabla `usuario`.
--
-- APLICACION MANUAL EN UNA BASE YA INICIALIZADA
--   Un volumen preexistente NO vuelve a ejecutar /docker-entrypoint-initdb.d,
--   asi que la migracion se aplica a mano. Desde la raiz del proyecto, en
--   cmd.exe (NO en PowerShell: su pipe corrompe la entrada por codificacion):
--
--     docker exec -i compustock_db psql -U postgres -d apt_erp -v ON_ERROR_STOP=1 < database\99_migracion_retiro_password.sql
--
--   Alternativa con psql en el host (si esta instalado):
--
--     psql -h localhost -p 5433 -U postgres -d apt_erp -v ON_ERROR_STOP=1 -f database/99_migracion_retiro_password.sql
--
--   Verificar el catalogo antes y despues (la columna debe desaparecer):
--
--     docker exec compustock_db psql -U postgres -d apt_erp -c "SELECT column_name FROM information_schema.columns WHERE table_name='usuario' ORDER BY ordinal_position;"
--
-- =====================================================

ALTER TABLE usuario DROP COLUMN IF EXISTS password;
